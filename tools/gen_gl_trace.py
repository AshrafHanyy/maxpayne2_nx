"""Generate source/gl_trace.c: error-checking wrappers for every GL import.

usage: python gen_gl_trace.py <gl2.h> <imports.c> <out.c>
Each wrapper calls the real function, then glGetError(); on error it logs
the call with its arguments (and the uniform name for glUniform* calls).
"""
import re
import sys

gl2h, imports_c, out = sys.argv[1:4]
protos = {}
for m in re.finditer(r'GL_APICALL\s+(.+?)\s+GL_APIENTRY\s+(gl\w+)\s*\(([^)]*)\);', open(gl2h).read()):
    protos[m.group(2)] = (m.group(1).strip(), m.group(3).strip())

names = sorted(set(re.findall(r'REAL\((gl\w+)\)', open(imports_c).read())))
names = [n for n in names if n not in ('glGetError',)]

FMT = {
    'GLenum': ('0x%x', '(unsigned)'), 'GLbitfield': ('0x%x', '(unsigned)'),
    'GLint': ('%d', '(int)'), 'GLsizei': ('%d', '(int)'), 'GLuint': ('%u', '(unsigned)'),
    'GLboolean': ('%d', '(int)'), 'GLfloat': ('%g', '(double)'), 'GLclampf': ('%g', '(double)'),
    'GLintptr': ('%ld', '(long)'), 'GLsizeiptr': ('%ld', '(long)'), 'GLchar': ('%d', '(int)'),
}

lines = [
    '/* gl_trace.c -- GENERATED by tools/gen_gl_trace.py, do not edit.',
    ' * Error-checking wrappers for the GL functions the game imports. */',
    '',
    '#include <GLES2/gl2.h>',
    '#include "gl_trace.h"',
    '',
]
table = []
for n in names:
    if n not in protos:
        print('no prototype for', n)
        continue
    ret, params = protos[n]
    plist = [] if params in ('void', '') else [p.strip() for p in params.split(',')]
    decl, call, fmts, vals = [], [], [], []
    for i, p in enumerate(plist):
        m = re.match(r'(.*?)(\w+)$', p)
        ptype, pname = m.group(1).strip(), m.group(2)
        decl.append(f'{ptype} {pname}')
        call.append(pname)
        if '*' in ptype:
            fmts.append('%p'); vals.append(f'(const void *){pname}')
        else:
            f, cast = FMT.get(ptype, ('%ld', '(long)'))
            fmts.append(f); vals.append(f'{cast}{pname}')
    sig = ', '.join(decl) if decl else 'void'
    is_uniform = n.startswith('glUniform')
    body = []
    if ret == 'void':
        body.append(f'  {n}({", ".join(call)});')
    else:
        body.append(f'  {ret} r = {n}({", ".join(call)});')
    if ret != 'void':
        # include the return value when tracing
        fmts.append('-> ' + ('%p' if '*' in ret else '%ld'))
        vals.append('(const void *)r' if '*' in ret else '(long)r')
    fmt = ', '.join(fmts)
    args = (', ' + ', '.join(vals)) if vals else ''
    loc = call[0] if is_uniform else '-1'
    body.append(f'  gl_trace_check("{n}", {loc}, {int(is_uniform)}, "{fmt}"{args});')
    if ret != 'void':
        body.append('  return r;')
    lines.append(f'static {ret} {n}_trace({sig}) {{')
    lines += body
    lines.append('}')
    lines.append('')
    table.append(f'  {{ "{n}", (void *){n}_trace }},')

lines.append('const gl_trace_entry gl_trace_table[] = {')
lines += table
lines.append('  { 0, 0 },')
lines.append('};')
open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
print(f'{len(table)} wrappers written')
